// Wires the workspace's optional slots at dev/build time (run by predev / prebuild).
// Other agents own components/imagine/* and lib/ml/*; the workspace imports them only when the files exist,
// so the property workspace builds and renders with or without them. Writes components/workspace/slots.generated.ts.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = process.cwd();
const has = (p) => existsSync(join(root, p));
const imagine = has("components/imagine/imagine-panel.tsx");
const survival = has("lib/ml/survival.ts");

const out = `// GENERATED by scripts/workspace-slots.mjs (predev / prebuild). Do not edit by hand.
// imagine panel: ${imagine ? "present" : "absent"}; survival model: ${survival ? "present" : "absent"}
import type { ComponentType } from "react";
import type { ImaginePanelProps } from "./imagine-types";

${
  imagine
    ? `import dynamic from "next/dynamic";
export const ImaginePanel: ComponentType<ImaginePanelProps> | null = dynamic(
  () => import("@/components/imagine/imagine-panel").then((m) => {
    const mod = m as unknown as Record<string, ComponentType<ImaginePanelProps> | undefined>;
    return (mod.ImaginePanel ?? mod.default)!;
  }),
  { loading: () => null },
);`
    : `export const ImaginePanel: ComponentType<ImaginePanelProps> | null = null;`
}
`;

const outSurvival = `// GENERATED by scripts/workspace-slots.mjs (predev / prebuild). Do not edit by hand.
// Server-only: the survival model is read on the server and handed to the workspace as plain data.
${survival ? `import * as survival from "@/lib/ml/survival";\nexport const survivalModule: unknown = survival;` : `export const survivalModule: unknown = null;`}
`;

const write = (p, s) => {
  const f = join(root, p);
  if (!existsSync(f) || readFileSync(f, "utf8") !== s) writeFileSync(f, s);
};
write("components/workspace/slots.generated.ts", out);
write("components/workspace/survival-slot.generated.ts", outSurvival);
console.log(`[workspace-slots] imagine: ${imagine ? "on" : "placeholder"}, survival: ${survival ? "on" : "placeholder"}`);
